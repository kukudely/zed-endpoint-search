import fs from 'node:fs/promises';
import path from 'node:path';
import { createJavaParser } from '../server/java.mjs';
import { EndpointIndex } from '../server/index.mjs';

const root = process.argv[2];
if (!root) throw Error('Usage: npm run benchmark -- PATH_TO_JAVA_PROJECT');
const base = path.resolve('.tmp/benchmarks'); await fs.mkdir(base, { recursive: true });
const cacheDir = await fs.mkdtemp(path.join(base, 'index-'));
const before = performance.now();
const parser = await createJavaParser();
const parserMs = Math.round(performance.now() - before);
const coldStart = performance.now();
const cold = new EndpointIndex({ root, cacheDir, parser, log: message => process.stderr.write(message + '\n') });
await cold.start({ watch: false }); await cold.ready;
const coldMs = Math.round(performance.now() - coldStart);
const all = cold.search('', Number.MAX_SAFE_INTEGER);
const samples = ['/api/health', '/api/users/settings'].map(query => ({ query, results: cold.search(query).map(item => ({ name: item.name, location: item.location })) }));
const coldStats = { ...cold.stats };
await cold.close();
const warmStart = performance.now();
const warm = new EndpointIndex({ root, cacheDir, parser }); await warm.start({ watch: false });
const warmAvailableMs = Math.round(performance.now() - warmStart);
const queryStart = performance.now(); const warmCount = warm.search('', Number.MAX_SAFE_INTEGER).length;
const queryMs = +(performance.now() - queryStart).toFixed(2);
await warm.ready;
const result = { root: path.resolve(root), measuredAt: new Date().toISOString(), parserMs, coldMs, warmAvailableMs, queryMs, endpoints: all.length, unresolved: all.filter(item => item.name.startsWith('@?')).length, warmCount, coldStats, warmStats: warm.stats, samples };
await warm.close(); parser.close();
await fs.writeFile(path.join(base, 'latest.json'), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
